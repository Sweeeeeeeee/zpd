"""Write the Latvian talk's numeric macros from the published research records."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    result = json.loads((ROOT / "results/local-cpu/summary.json").read_text())
    study = result["latvia_policy_comparison"]
    ar = result["latvia_paired_ar"]
    model = result["completed_training"]
    cohorts = result["imo_student_scores"]
    chiang_mai = next(item for item in cohorts["editions"] if item["year"] == 2015)
    scores = {item["number"]: item["total"] / chiang_mai["contestants"] for item in chiang_mai["items"]}
    steps = ar["original_appendix_steps"].values()
    checked = sum(sum(group.values()) for group in steps)
    explicit = sum(group["follows"] for group in steps)
    reconstructed = sum(ar["restored_by_construction_equations"].values())
    status = result["translations"]
    values = {
        "ReducedWins": result["latvia_restricted_deduction"]["reduced_wins"],
        "ReducedRules": result["latvia_restricted_deduction"]["reduced_rules"],
        "Candidates": sum(status.values()), "Cases": study["cases"], "Runs": study["runs"],
        "ProvedOn": len(study["domains"]["full"]["common_wins"]),
        "ProvedOff": len(study["domains"]["full_no_ar"]["any_wins"]),
        "PredCases": model["n"], "TopOne": model["top1"], "TopFour": model["top4"],
        "JgexTried": result["proofs"]["jgex_ag_231"]["small_final"]["tested"],
        "JgexWon": result["proofs"]["jgex_ag_231"]["small_final"]["proved"],
        "ImoTried": result["proofs"]["imo"]["small_final"]["tested"],
        "ImoWon": result["proofs"]["imo"]["small_final"]["proved"],
        "Steps": checked, "Explicit": explicit, "Reconstructed": reconstructed,
        "Unresolved": checked - explicit - reconstructed, "Transcripts": ar["selected"],
        "Cohorts": len(cohorts["editions"]), "Higher": cohorts["comparisons"]["proved_higher"],
        "ImoParticipants": chiang_mai["contestants"],
        "ImoThreeMean": f"{scores[3]:.2f}".replace(".", ","),
        "ImoFourMean": f"{scores[4]:.2f}".replace(".", ","),
    }
    for domain, suffix in (("full", "On"), ("full_no_ar", "Off")):
        for policy, label in (("deduction", "Ded"), ("heuristics", "Heur"), ("combined", "Model")):
            r = study["domains"][domain]["policies"][policy]
            values[label + suffix] = r["outcomes"]["proved"]
    text = "% Generated by scripts/presentation_data.py from results/local-cpu/summary.json.\n"
    text += "".join(f"\\newcommand{{\\talk{key}}}{{{value}}}\n" for key, value in values.items())
    target = ROOT / "zpd_darbs/prezentacija/dati.tex"
    target.write_text(text)


if __name__ == "__main__":
    main()
