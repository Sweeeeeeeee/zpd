"""Write every Newclid rule, and which rule sets contain it, to docs/rules.md.

    python -m ddar.list_rules            # regenerate docs/rules.md
    python -m ddar.list_rules --print    # print to the terminal instead
"""

from __future__ import annotations

import argparse
from pathlib import Path

import ddar  # noqa: F401  (puts the yuclid binary on PATH)
from newclid import all_rules
from newclid.all_rules import ALL_RULES, DEACTIVATED_RULES, DEFAULT_RULES
from py_yuclid.yuclid_adapter import YUCLID_RULES

ROOT = Path(__file__).resolve().parents[1]


def render() -> str:
    default = {r.id for r in DEFAULT_RULES}
    yuclid = {r.id for r in YUCLID_RULES}
    off = {r.id for r in DEACTIVATED_RULES}
    lines = [
        "# Deduction rules",
        "",
        "Generated by `python -m ddar.list_rules` from the installed Newclid "
        f"(`{Path(all_rules.__file__).relative_to(ROOT) if ROOT in Path(all_rules.__file__).parents else all_rules.__file__}`).",
        "",
        "Where rules live:",
        "",
        "| what | where |",
        "|---|---|",
        "| rule definitions (premises => conclusions) | `newclid/all_rules.py` in the Newclid package: one `Rule(...)` constant per rule |",
        "| Newclid's default set (`default` column) | `DEFAULT_RULES` at the end of the same file |",
        "| yuclid's rules (`yuclid` column) | compiled into the `yuclid` binary; the ids are listed in `YUCLID_RULES` in `py_yuclid/yuclid_adapter.py` |",
        "| which rules a run uses | `enabled_rules` / `disabled_rules` in `ddar/configs/*.json`, filtered by `ddar/rule_config.py` |",
        "",
        "r00-r42 come from the original AlphaGeometry; later ids were added by Newclid. "
        "Missing numbers (r32, r33, r38-r40) were removed upstream.",
        "",
        f"{len(ALL_RULES)} rules, {len(default)} in the default set, {len(yuclid)} in yuclid.",
        "",
        "| id | name | default | yuclid | premises => conclusions |",
        "|---|---|---|---|---|",
    ]
    for rule in sorted(ALL_RULES, key=lambda r: r.id):
        flag_default = "off" if rule.id in off else ("yes" if rule.id in default else "")
        flag_yuclid = "yes" if rule.id in yuclid else ""
        body = f"{', '.join(rule.premises_txt)} => {', '.join(rule.conclusions_txt)}"
        lines.append(f"| {rule.id} | {rule.description} | {flag_default} | {flag_yuclid} | `{body}` |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--print", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.print:
        print(text)
    else:
        (ROOT / "docs/rules.md").write_text(text)
        print(f"wrote {ROOT / 'docs/rules.md'}")


if __name__ == "__main__":
    main()
