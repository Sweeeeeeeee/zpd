"""Write the pipeline configs for the proposer comparison (docs/models.md).

One config per (domain, proposer) in pipeline/configs/compare/<domain>/<proposer>.json.
Everything but the proposer is the same: the domain's DDAR rules, depth 1 (at
most one auxiliary point), beam 4, 60 s after loading (domains need the
slow Python DDAR engine, docs/domains.md). Light models get 2 GB,
big ones 3 GB (a 0.6B model in bfloat16 alone is ~1.2 GB); report them apart.

    python bench/compare_configs.py        # rewrites the folder
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "pipeline/configs/compare"
DOMAINS = ["full", "no_similarity", "circles"]  # with AR; see docs/domains.md

HF = "pipeline.hf_tool:HFLMTool"
PROPOSERS: dict[str, tuple[dict | None, int]] = {
    # name: (tool spec or None for DDAR alone, memory MB)
    "ddar": (None, 2048),
    "heuristics": ({"kinds": ["midpoint", "circumcenter", "foot"], "max_candidates": 8}, 2048),
    "mini": ({"checkpoint": "geo-lm/runs/mini/best.pt"}, 2048),
    "mini_long": ({"checkpoint": "geo-lm/runs/mini_long/best.pt"}, 2048),
    "mid": ({"checkpoint": "geo-lm/runs/mid/best.pt"}, 2048),
    "smollm2_360m": ({"class": HF, "model": "HuggingFaceTB/SmolLM2-360M-Instruct",
                      "prompt": "fewshot", "name": "smollm2_360m"}, 2048),
    "genesisgeo": ({"class": HF, "model": "models/hf/GenesisGeo",
                    "prompt": "genesisgeo", "name": "genesisgeo"}, 3072),
    "qwen25_1_5b": ({"class": HF, "model": "Qwen/Qwen2.5-1.5B-Instruct",
                     "prompt": "fewshot", "name": "qwen25_1_5b"}, 4096),
}


def config(domain: str, proposer: str) -> dict:
    spec, memory = PROPOSERS[proposer]
    tools: dict = {"ddar": {"enabled": True, "options": {"config": f"ddar/configs/domains/{domain}.json", "seed": 0}}}
    order: list[str] = []
    if spec is not None:
        spec = dict(spec)
        if proposer == "heuristics":
            tools["heuristics"] = {"enabled": True, "options": spec}
        else:
            cls = spec.pop("class", None)
            options = {"beam_size": 4, "max_candidates": 4, "max_new_tokens": 48, **spec}
            tools[proposer] = {"enabled": True, "options": options}
            if cls:
                tools[proposer]["class"] = cls
            else:  # geo-lm checkpoints use the built-in transformer tool
                tools["transformer"] = tools.pop(proposer)
        order = [k for k in tools if k != "ddar"]
    return {
        "_comment": f"Proposer comparison: domain '{domain}', proposer '{proposer}', one aux point. Generated by bench/compare_configs.py.",
        "tools": tools,
        "proposer_order": order,
        "strict_tools": True,
        "search": {"max_depth": 1, "branching": 8, "max_frontier": 8, "max_ddar_calls": 20, "time_limit": 0},
        "budget": {"time_s": 60, "memory_mb": memory, "cpu_s": 0, "load_s": 120},
    }


def main() -> None:
    for domain in DOMAINS:
        (OUT / domain).mkdir(parents=True, exist_ok=True)
        for proposer in PROPOSERS:
            path = OUT / domain / f"{proposer}.json"
            path.write_text(json.dumps(config(domain, proposer), indent=2) + "\n")
    print(f"wrote {len(DOMAINS) * len(PROPOSERS)} configs to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
